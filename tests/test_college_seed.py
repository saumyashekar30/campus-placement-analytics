"""Static academic seed checks (no Oracle server required).

These tests verify the checked-in seed, SQL setup order and schema relationships.
They are not a substitute for executing the DDL and data on Oracle itself.
"""
import re
import unittest
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = (ROOT / "database/01_schema.sql").read_text(encoding="utf-8")
SEED = (ROOT / "database/02_seed_data.sql").read_text(encoding="utf-8")
SETUP = (ROOT / "database/run_all.sql").read_text(encoding="utf-8")
SYNC = (ROOT / "database/06_sync_identity.sql").read_text(encoding="utf-8")


def inserts(table):
    return re.findall(r"INSERT INTO\s+" + table + r"\s*\([^;]+?;", SEED, re.I | re.S)


class CollegeSeedChecks(unittest.TestCase):
    def test_expected_entity_count_and_kpis(self):
        self.assertEqual(len(re.findall(r"^CREATE TABLE\s+", SCHEMA, re.I | re.M)), 11)
        self.assertEqual([len(inserts(t)) for t in
                          ("STUDENT", "COMPANY", "APPLICATION", "INTERVIEW", "PLACEMENT")],
                         [10, 5, 16, 16, 6])

        statuses = Counter(re.findall(
            r"'(Applied|Shortlisted|In Review|Rejected|Selected)'",
            "".join(inserts("APPLICATION"))))
        self.assertEqual(statuses["Selected"], 6)
        self.assertEqual(statuses["Rejected"], 1)
        self.assertEqual(sum(statuses.values()), 16)

        interviews = Counter(re.findall(
            r"'(Passed|Failed|Scheduled|Pending)'",
            "".join(inserts("INTERVIEW"))))
        self.assertEqual(interviews["Passed"], 15)
        self.assertEqual(interviews["Failed"], 1)

    def test_primary_key_generators_are_resynchronized(self):
        identity_tables = re.findall(
            r"CREATE TABLE\s+(\w+)\s*\(\s*(\w+)\s+NUMBER GENERATED BY DEFAULT AS IDENTITY",
            SCHEMA, re.I)
        self.assertEqual(len(identity_tables), 8)
        for table, key in identity_tables:
            with self.subTest(table=table):
                self.assertRegex(
                    SYNC.upper(),
                    rf"ALTER TABLE\s+{table.upper()}\s+MODIFY\s+{key.upper()}\s+"
                    r"GENERATED BY DEFAULT AS IDENTITY\s*\(START WITH LIMIT VALUE\);"
                )
        self.assertLess(SETUP.index("@@02_seed_data.sql"), SETUP.index("@@06_sync_identity.sql"))
        self.assertLess(SETUP.index("@@06_sync_identity.sql"), SETUP.index("@@03_queries.sql"))

    def test_reported_packages_come_from_seed(self):
        rows = inserts("PLACEMENT")
        package_values = []
        for sql in rows:
            # package_offered appears immediately before acceptance_status in seed INSERT.
            m = re.search(r",\s*(\d+\.\d+)\s*,\s*'Accepted'\s*,", sql)
            self.assertIsNotNone(m, "Missing accepted offer package")
            package_values.append(float(m.group(1)))
        self.assertEqual(max(package_values), 24)
        self.assertEqual(min(package_values), 5.5)
        self.assertAlmostEqual(round(sum(package_values)/len(package_values), 2), 12.92)

if __name__ == "__main__":
    unittest.main()
