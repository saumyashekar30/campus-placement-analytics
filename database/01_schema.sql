SET SQLBLANKLINES ON;
SET DEFINE OFF;
SET FEEDBACK ON;

-- Clean up existing tables safely in reverse dependency order
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'PLACEMENT', 'INTERVIEW', 'APPLICATION', 'COMPANY_SKILL', 
        'COMPANY_BRANCH', 'COMPANY', 'INTERNSHIP', 'PROJECT', 
        'CERTIFICATION', 'STUDENT_SKILL', 'STUDENT'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ============================================================================
-- 1. STUDENT TABLE
-- Stores primary academic and demographic data for registered candidates.
-- ============================================================================
CREATE TABLE STUDENT (
    student_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name        VARCHAR2(100)           NOT NULL,
    email               VARCHAR2(100)           NOT NULL,
    phone               VARCHAR2(15),
    branch              VARCHAR2(20)            NOT NULL,
    cgpa                NUMBER(3,2)             NOT NULL,
    tenth_percentage    NUMBER(5,2)             NOT NULL,
    twelfth_percentage  NUMBER(5,2)             NOT NULL,
    backlogs            NUMBER(2)   DEFAULT 0   NOT NULL,
    resume_url          VARCHAR2(255),
    created_at          DATE        DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_student_email         UNIQUE (email),
    CONSTRAINT chk_student_cgpa         CHECK (cgpa >= 0.00 AND cgpa <= 10.00),
    CONSTRAINT chk_student_tenth        CHECK (tenth_percentage >= 0.00 AND tenth_percentage <= 100.00),
    CONSTRAINT chk_student_twelfth      CHECK (twelfth_percentage >= 0.00 AND twelfth_percentage <= 100.00),
    CONSTRAINT chk_student_backlogs     CHECK (backlogs >= 0)
);

-- ============================================================================
-- 2. STUDENT_SKILL TABLE (Normalized Multi-valued Attribute)
-- Relationship: One Student -> Many Skills
-- ============================================================================
CREATE TABLE STUDENT_SKILL (
    student_id          NUMBER                  NOT NULL,
    skill_name          VARCHAR2(50)            NOT NULL,
    proficiency_level   VARCHAR2(20) DEFAULT 'Intermediate' NOT NULL,
    CONSTRAINT pk_student_skill         PRIMARY KEY (student_id, skill_name),
    CONSTRAINT fk_studskill_student     FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_studskill_level      CHECK (proficiency_level IN ('Beginner', 'Intermediate', 'Advanced', 'Expert'))
);

-- ============================================================================
-- 3. CERTIFICATION TABLE
-- Relationship: One Student -> Many Certifications
-- ============================================================================
CREATE TABLE CERTIFICATION (
    certification_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER                  NOT NULL,
    cert_name           VARCHAR2(150)           NOT NULL,
    issuing_organization VARCHAR2(100)          NOT NULL,
    issue_date          DATE                    NOT NULL,
    expiry_date         DATE,
    credential_id       VARCHAR2(100),
    CONSTRAINT fk_cert_student          FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_cert_dates           CHECK (expiry_date IS NULL OR expiry_date >= issue_date)
);

-- ============================================================================
-- 4. PROJECT TABLE
-- Relationship: One Student -> Many Projects
-- ============================================================================
CREATE TABLE PROJECT (
    project_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER                  NOT NULL,
    project_title       VARCHAR2(150)           NOT NULL,
    tech_stack          VARCHAR2(200)           NOT NULL,
    description         VARCHAR2(1000),
    project_url         VARCHAR2(255),
    start_date          DATE,
    end_date            DATE,
    CONSTRAINT fk_proj_student          FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_proj_dates           CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

-- ============================================================================
-- 5. INTERNSHIP TABLE
-- Relationship: One Student -> Many Internships
-- ============================================================================
CREATE TABLE INTERNSHIP (
    internship_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER                  NOT NULL,
    company_name        VARCHAR2(100)           NOT NULL,
    role                VARCHAR2(100)           NOT NULL,
    start_date          DATE                    NOT NULL,
    end_date            DATE,
    description         VARCHAR2(1000),
    CONSTRAINT fk_intern_student        FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT chk_intern_dates         CHECK (end_date IS NULL OR end_date >= start_date)
);

-- ============================================================================
-- 6. COMPANY TABLE (Placement Drive)
-- Defines company job drive details and per-company dynamic academic eligibility.
-- ============================================================================
CREATE TABLE COMPANY (
    company_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name            VARCHAR2(100)           NOT NULL,
    job_role                VARCHAR2(100)           NOT NULL,
    required_cgpa           NUMBER(3,2) DEFAULT 0.00 NOT NULL,
    min_tenth_percentage    NUMBER(5,2) DEFAULT 0.00 NOT NULL,
    min_twelfth_percentage  NUMBER(5,2) DEFAULT 0.00 NOT NULL,
    max_backlogs            NUMBER(2)   DEFAULT 0    NOT NULL,
    package                 NUMBER(10,2)             NOT NULL,
    job_description         VARCHAR2(2000),
    application_deadline    DATE                    NOT NULL,
    drive_date              DATE,
    CONSTRAINT chk_comp_cgpa            CHECK (required_cgpa >= 0.00 AND required_cgpa <= 10.00),
    CONSTRAINT chk_comp_tenth           CHECK (min_tenth_percentage >= 0.00 AND min_tenth_percentage <= 100.00),
    CONSTRAINT chk_comp_twelfth         CHECK (min_twelfth_percentage >= 0.00 AND min_twelfth_percentage <= 100.00),
    CONSTRAINT chk_comp_backlogs        CHECK (max_backlogs >= 0),
    CONSTRAINT chk_comp_package         CHECK (package >= 0.00)
);

-- ============================================================================
-- 7. COMPANY_BRANCH TABLE (Normalized Allowed Branches)
-- Relationship: One Company -> Many Allowed Branches
-- Avoids storing comma-separated strings like "CSE,ECE,IT".
-- ============================================================================
CREATE TABLE COMPANY_BRANCH (
    company_id          NUMBER                  NOT NULL,
    branch_name         VARCHAR2(20)            NOT NULL,
    CONSTRAINT pk_company_branch        PRIMARY KEY (company_id, branch_name),
    CONSTRAINT fk_compbr_company        FOREIGN KEY (company_id) REFERENCES COMPANY(company_id) ON DELETE CASCADE
);

-- ============================================================================
-- 8. COMPANY_SKILL TABLE (Normalized Required Skills)
-- Relationship: One Company -> Many Required Skills
-- ============================================================================
CREATE TABLE COMPANY_SKILL (
    company_id          NUMBER                  NOT NULL,
    skill_name          VARCHAR2(50)            NOT NULL,
    min_proficiency     VARCHAR2(20) DEFAULT 'Intermediate',
    CONSTRAINT pk_company_skill         PRIMARY KEY (company_id, skill_name),
    CONSTRAINT fk_compsk_company        FOREIGN KEY (company_id) REFERENCES COMPANY(company_id) ON DELETE CASCADE,
    CONSTRAINT chk_compsk_proficiency   CHECK (min_proficiency IN ('Beginner', 'Intermediate', 'Advanced', 'Expert'))
);

-- ============================================================================
-- 9. APPLICATION TABLE
-- Relationship: One Student -> Many Applications; One Company -> Many Applications
-- Tracks the application lifecycle.
-- ============================================================================
CREATE TABLE APPLICATION (
    application_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER                  NOT NULL,
    company_id          NUMBER                  NOT NULL,
    application_date    DATE        DEFAULT SYSDATE NOT NULL,
    status              VARCHAR2(30) DEFAULT 'Applied' NOT NULL,
    CONSTRAINT fk_app_student           FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_app_company           FOREIGN KEY (company_id) REFERENCES COMPANY(company_id) ON DELETE CASCADE,
    CONSTRAINT uq_student_company_app   UNIQUE (student_id, company_id),
    CONSTRAINT chk_app_status           CHECK (status IN ('Applied', 'Shortlisted', 'In Review', 'Rejected', 'Selected'))
);

-- ============================================================================
-- 10. INTERVIEW TABLE
-- Relationship: One Student -> Many Interviews; One Company -> Many Interviews
-- Linked via APPLICATION_ID to preserve referential integrity.
-- ============================================================================
CREATE TABLE INTERVIEW (
    interview_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      NUMBER                  NOT NULL,
    round_number        NUMBER(2)               NOT NULL,
    round_name          VARCHAR2(50)            NOT NULL,
    interview_date      DATE                    NOT NULL,
    score               NUMBER(5,2),
    status              VARCHAR2(20) DEFAULT 'Scheduled' NOT NULL,
    feedback            VARCHAR2(1000),
    CONSTRAINT fk_interview_app         FOREIGN KEY (application_id) REFERENCES APPLICATION(application_id) ON DELETE CASCADE,
    CONSTRAINT uq_app_round             UNIQUE (application_id, round_number),
    CONSTRAINT chk_interview_round      CHECK (round_number >= 1),
    CONSTRAINT chk_interview_score      CHECK (score IS NULL OR (score >= 0.00 AND score <= 100.00)),
    CONSTRAINT chk_interview_status     CHECK (status IN ('Scheduled', 'Passed', 'Failed', 'Pending'))
);

-- ============================================================================
-- 11. PLACEMENT TABLE
-- Relationship: One Student -> Placement Record (1:1 enforced by UNIQUE on student_id)
--               One Company -> Many Placement Records (1:N)
-- ============================================================================
CREATE TABLE PLACEMENT (
    placement_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER                  NOT NULL,
    company_id          NUMBER                  NOT NULL,
    application_id      NUMBER,
    offer_date          DATE        DEFAULT SYSDATE NOT NULL,
    package_offered     NUMBER(10,2)            NOT NULL,
    acceptance_status   VARCHAR2(20) DEFAULT 'Accepted' NOT NULL,
    joining_date        DATE,
    CONSTRAINT uq_placement_student     UNIQUE (student_id),
    CONSTRAINT uq_placement_app         UNIQUE (application_id),
    CONSTRAINT fk_place_student         FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_place_company         FOREIGN KEY (company_id) REFERENCES COMPANY(company_id) ON DELETE CASCADE,
    CONSTRAINT fk_place_app             FOREIGN KEY (application_id) REFERENCES APPLICATION(application_id) ON DELETE SET NULL,
    CONSTRAINT chk_place_package        CHECK (package_offered >= 0.00),
    CONSTRAINT chk_place_status         CHECK (acceptance_status IN ('Accepted', 'Declined', 'Pending'))
);

COMMIT;
